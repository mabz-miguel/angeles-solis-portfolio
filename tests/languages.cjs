const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true, channel:"chrome"});
 const page = await browser.newPage();
 const base = process.env.TEST_BASE || 'http://127.0.0.1:8765/';
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'index.html#contact');
 await page.locator('[data-language="en"]').click();
 await page.waitForURL('**/en/index.html#contact');
 assert.equal(await page.locator('html').getAttribute('lang'),'en');
 assert.match(await page.locator('a[href$="angeles-solis-cv-en.pdf"]').getAttribute('href'),/cv-en.pdf$/);
 await page.goto(base+'en/complete-archive.html');
 await page.locator('.archive-entry').first().waitFor();
 assert.equal(await page.locator('.archive-entry').count(),22);
 await page.locator('[data-filter="painting"]').click();
 assert.match(await page.locator('#archive-count').textContent(),/projects?$/);
 await page.goto(base+'en/project-detail.html?id=vaciados-rabasf&from=vaciados');
 await page.locator('#detail-main').waitFor();
 assert.match(await page.locator('#hero-title').textContent(),/Cast/);
 await page.locator('[data-language="es"]').click();
 await page.waitForURL('**/project-detail.html?id=vaciados-rabasf&from=vaciados');
 assert.equal(await page.locator('html').getAttribute('lang'),'es');
 await page.locator('#detail-main').waitFor();
 assert.match(await page.locator('#hero-title').textContent(),/Vaciados/);
 await page.goto(base+'en/project-detail.html?id=not-real');
 await page.getByText('Project not found.',{exact:false}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'en/index.html');
 await page.locator('[data-language="es"]').waitFor({state:'visible'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 await browser.close(); console.log('PASS: language navigation, filters, project content, CV links, error state and mobile layout');
})().catch(e=>{console.error(e);process.exit(1)});
